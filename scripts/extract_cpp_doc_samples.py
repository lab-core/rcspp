"""Write the C++ code blocks of Markdown pages into one translation unit that must compile.

The build compiles the output (target `docs-samples`), so a sample that stops compiling fails the
build, and the error points at the Markdown file and line through `#line` directives.

Each ```cpp block becomes the body of its own function, inside its own namespace, after
`using namespace rcspp;`, which the pages state once at the top. The function receives `graph`, a
`ResourceGraph<RealResource, IntResource>`, and `ub`, a `double`, which most fragments use without
declaring; a block that declares its own shadows them. `#include` lines move to the top of the
file.

An HTML comment before a block changes how it is compiled; MyST does not render it, and it may span
several lines:

    <!-- docs-check: given DECLARATIONS -->  compiled after DECLARATIONS, the names a fragment
                                             takes from the reader (`double capacity = 10.0;`)
    <!-- docs-check: file-scope -->          compiled at namespace scope, as written: class or
                                             template definitions, which a function cannot hold
    <!-- docs-check: skip -->                not compiled: an interface sketch, or `…` placeholders
    <!-- docs-check: broken -->              not compiled, and reported on every run: a sample
                                             that is wrong and waits for a fix

usage: python extract_cpp_doc_samples.py --output <file.cpp> --root <repo> <page.md>...
"""

import argparse
import re
from pathlib import Path

FENCE = re.compile(r"^(\s*)(`{3,})\s*(cpp|c\+\+)\s*$")
MARKER = re.compile(r"^\s*<!--\s*docs-check:\s*([\w-]+)(.*?)-->\s*$")
INCLUDE = re.compile(r"^\s*#\s*include\b")

PRELUDE = """\
// Generated by scripts/extract_cpp_doc_samples.py from the C++ code blocks of the docs.
// Do not edit: fix the Markdown page that the #line directives name.

#include <cstddef>
#include <iostream>
#include <map>
#include <memory>
#include <set>
#include <string>
#include <tuple>
#include <unordered_map>
#include <utility>
#include <vector>

#include "rcspp/rcspp.hpp"

#if defined(__GNUC__)
#pragma GCC diagnostic ignored "-Wunused-variable"
#pragma GCC diagnostic ignored "-Wunused-but-set-variable"
#pragma GCC diagnostic ignored "-Wunused-local-typedefs"
#pragma GCC diagnostic ignored "-Wunused-parameter"
#pragma GCC diagnostic ignored "-Wshadow"
#elif defined(_MSC_VER)
#pragma warning(disable : 4101 4189 4100 4456 4457 4458 4459)
#endif
"""

# The names the docs use without declaring them, passed to every block as parameters.
CONTEXT = """\
    [[maybe_unused]] rcspp::ResourceGraph<rcspp::RealResource, rcspp::IntResource>& graph,
    [[maybe_unused]] double ub"""


def blocks(path: Path):
    """Yield (marker, its argument, its line, the block's first line, the block's lines) for each
    C++ block of a page; line numbers are 1-based."""
    lines = path.read_text(encoding="utf-8").splitlines()
    i = 0
    while i < len(lines):
        m = FENCE.match(lines[i])
        if not m:
            i += 1
            continue
        fence = m.group(2)
        marker, argument, marker_line = None, "", i
        k = i - 1
        while k >= 0 and not lines[k].strip():
            k -= 1
        if k >= 0 and lines[k].rstrip().endswith("-->"):
            top = k
            while top > 0 and "<!--" not in lines[top]:
                top -= 1
            comment = " ".join(line.strip() for line in lines[top : k + 1])
            if mm := MARKER.match(comment):
                marker, argument, marker_line = mm.group(1), mm.group(2).strip(), top + 1
        start = i + 1
        j = start
        while j < len(lines) and not lines[j].strip().startswith(fence):
            j += 1
        yield marker, argument, marker_line, start + 1, lines[start:j]
        i = j + 1


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--root", required=True, type=Path)
    parser.add_argument("pages", nargs="+", type=Path)
    args = parser.parse_args()

    includes = []
    bodies = []
    broken = []
    n = 0
    for page in sorted(args.pages):
        rel = page.resolve().relative_to(args.root.resolve()).as_posix()
        for marker, argument, marker_line, first_line, lines in blocks(page):
            where_md = f"{rel}:{marker_line}"
            if marker not in (None, "given", "file-scope", "skip", "broken"):
                raise SystemExit(f"{where_md}: unknown docs-check marker '{marker}'")
            if (marker == "given") != bool(argument):
                raise SystemExit(f"{where_md}: only 'given' takes declarations")
            if marker == "skip":
                continue
            if marker == "broken":
                broken.append(where_md)
                continue
            n += 1
            code = []
            for line in lines:
                if INCLUDE.match(line):
                    if line.strip() not in includes:
                        includes.append(line.strip())
                    code.append("")  # keep the line numbers
                else:
                    code.append(line)
            body = "\n".join(code)
            where = f'#line {first_line} "{rel}"'
            if marker == "file-scope":
                bodies.append(
                    f"namespace docs_sample_{n} {{\nusing namespace rcspp;\n{where}\n"
                    f"{body}\n}}  // namespace\n"
                )
            else:
                given = f'#line {marker_line} "{rel}"\n        {argument}\n' if argument else ""
                bodies.append(
                    f"namespace docs_sample_{n} {{\nvoid sample(\n{CONTEXT}) {{\n"
                    f"    using namespace rcspp;\n"
                    f"    {{\n{given}{where}\n{body}\n    }}\n}}\n}}  // namespace\n"
                )

    text = PRELUDE + "".join(f"{inc}\n" for inc in includes) + "\n" + "\n".join(bodies)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(f"{n} C++ doc samples written to {args.output}")
    for where_md in broken:
        print(f"warning: {where_md}: C++ doc sample marked broken, not compiled")


if __name__ == "__main__":
    main()
