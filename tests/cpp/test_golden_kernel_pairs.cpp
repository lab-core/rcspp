/// @brief The strategy and direction pairs the kernel adds.
enum class Pair { AStarBackward, PushingBackward, PullingBackward, AStarBidirectional };

/// @brief The name of @p pair in a row key.
inline const char* pair_name(Pair pair) {
    switch (pair) {
        case Pair::AStarBackward:
            return "astar_backward";
        case Pair::PushingBackward:
            return "pushing_backward";
        case Pair::PullingBackward:
            return "pulling_backward";
        case Pair::AStarBidirectional:
            return "astar_bidirectional";
    }
    return "?";
}

/// @brief A backward search by @p Strategy, built by @c create_algorithm, under @p v.
template <typename Strategy>
gl::Outcome backward_outcome(AlgorithmParams<gl::ForwardList> p, const gl::Variant& v,
                             ResourceGraph<RealResource>* g) {
    p.direction = SearchDirection::Backward;
    auto a = g->create_algorithm<Strategy>(p);
    return gl::finish(a, g, v);
}

/// @brief Runs @p pair under setting @p v on @p g.
inline gl::Outcome run_pair(Pair pair, const gl::Variant& v, ResourceGraph<RealResource>* g) {
    auto p = gl::params_for<AlgorithmParams<gl::ForwardList>>(v);
    switch (pair) {
        case Pair::AStarBackward:
            return backward_outcome<strategy::AStar>(p, v, g);
        case Pair::PushingBackward:
            return backward_outcome<strategy::Pushing>(p, v, g);
        case Pair::PullingBackward:
            return backward_outcome<strategy::Pulling>(p, v, g);
        case Pair::AStarBidirectional:
            return gl::bidirectional_outcome<strategy::AStar>(p, v, g);
    }
    return {};
}

