/// @brief The heuristics.
enum class Heuristic {
    Greedy,
    Tabu,
    ImprovingTabu,
    Diversification,
};

/// @brief The name of @p h in a row key.
inline const char* heuristic_name(Heuristic h) {
    switch (h) {
        case Heuristic::Greedy:
            return "greedy";
        case Heuristic::Tabu:
            return "tabu";
        case Heuristic::ImprovingTabu:
            return "improving_tabu";
        case Heuristic::Diversification:
            return "diversification";
    }
    return "?";
}

/// @brief A @p Strategy search under heuristics setting @p v, summarised with its status.
template <typename Strategy>
gl::Outcome outcome(const gl::Variant& v, bool finite_budget, ResourceGraph<RealResource>* g) {
    auto a = g->create_algorithm<Strategy>(
        gl::heuristic_params<AlgorithmParams<gl::ForwardList>>(v, finite_budget, *g));
    const auto r = g->solve(a.get(), v.upper_bound, v.preprocess);
    gl::Outcome o = gl::summarise(r, 0);
    o.status = static_cast<size_t>(r.status);
    return o;
}

/// @brief Runs @p h under heuristics setting @p v on @p g.
inline gl::Outcome run_heuristic(Heuristic h, const gl::Variant& v,
                                 ResourceGraph<RealResource>* g) {
    switch (h) {
        case Heuristic::Greedy:
            return outcome<strategy::Greedy>(v, false, g);
        case Heuristic::Tabu:
            return outcome<strategy::Tabu>(v, true, g);
        case Heuristic::ImprovingTabu:
            return outcome<strategy::ImprovingTabu>(v, true, g);
        case Heuristic::Diversification:
            return outcome<strategy::Diversification<>>(v, true, g);
    }
    return {};
}

